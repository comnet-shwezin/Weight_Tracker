/**
 * Utility helper to format numbers and text translations
 */
export function getTranslation(lang: 'my' | 'en' | 'ja', key: keyof typeof translations['my']) {
  return translations[lang][key] || translations['en'][key];
}

export function formatBurmeseNumbers(value: number | string, lang: 'my' | 'en' | 'ja'): string {
  if (lang !== 'my') return String(value);
  const myNumbers = ['၀', '၁', '၂', '၃', '၄', '၅', '၆', '၇', '၈', '၉'];
  return String(value).replace(/[0-9]/g, (w) => myNumbers[parseInt(w, 10)]);
}
